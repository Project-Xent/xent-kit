function get()
  local events = {}
  for _, def in ipairs(event_defs) do events[def.key] = def end
  local public = {}
  for _, control in ipairs(controls) do
    if not control.internal then public[#public + 1] = control end
  end
  return {
    prop_order = prop_order,
    props = props,
    properties = properties,
    event_defs = event_defs,
    events = events,
    controls = controls,
    public = public,
    kinds = kinds,
    enums = enums,
    structs = structs,
  }
end
