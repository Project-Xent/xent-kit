#include "xtk_controls_internal.h"

XtkLocalId xtk_fonticon_create(XtkTxn *txn, XtkNodeRef parent, XtkFontIconProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_FONTICON, parent, props, &xtk_pack_fonticon);
}

