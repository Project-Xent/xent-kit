XtkLocalId xtk_suggest_create(XtkTxn *txn, XtkNodeRef parent, XtkSuggestProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_SUGGEST, parent, props, &xtk_pack_suggest);
}

