XtkLocalId xtk_infobar_create(XtkTxn *txn, XtkNodeRef parent, XtkInfoBarProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_INFOBAR, parent, props, &xtk_pack_infobar);
}

