XtkLocalId xtk_progress_create(XtkTxn *txn, XtkNodeRef parent, XtkProgressProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_PROGRESS, parent, props, &xtk_pack_progress);
}

