XtkLocalId xtk_textbox_create(XtkTxn *txn, XtkNodeRef parent, XtkTextBoxProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_TEXTBOX, parent, props, &xtk_pack_textbox);
}

