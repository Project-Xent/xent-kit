XtkLocalId xtk_checkbox_create(XtkTxn *txn, XtkNodeRef parent, XtkCheckBoxProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_CHECKBOX, parent, props, &xtk_pack_checkbox);
}

