#include "xtk_controls_internal.h"

XtkLocalId xtk_commandbar_create(XtkTxn *txn, XtkNodeRef parent, XtkCommandBarProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_COMMANDBAR, parent, props, &xtk_pack_commandbar);
}

