XtkLocalId xtk_splitview_create(XtkTxn *txn, XtkNodeRef parent, XtkSplitViewProps const *props) {
	return xtk_controls_create(txn, XTK_CTRL_SPLITVIEW, parent, props, &xtk_pack_splitview);
}

